import Foundation
@testable import BalanceCore

final class RefreshSchedulerTests {
    func testBrowserReconnectMergesWithWakeAndInFlightRecovery() {
        var scheduler = readyScheduler()
        scheduler.trigger(.connectionAvailable, at: 10)
        scheduler.trigger(.wake, at: 10.5)
        scheduler.trigger(.connectionAvailable, at: 11)
        expectEqual(scheduler.nextDueAt, 13)
        expectTrue(scheduler.beginIfDue(at: 13))
        scheduler.trigger(.connectionAvailable, at: 14)
        scheduler.trigger(.connectionAvailable, at: 15)
        expectNil(scheduler.nextDueAt)
        expectTrue(scheduler.hasPendingRefresh)
        scheduler.finish(at: 20, succeeded: false)
        expectEqual(scheduler.nextDueAt, 22)
        expectTrue(scheduler.beginIfDue(at: 22))
        scheduler.finish(at: 23, succeeded: true)
        expectEqual(scheduler.nextDueAt, 323)
        expectFalse(scheduler.hasPendingRefresh)
    }

    func testStartupWaitsForOnlineAndLateCallbacksDoNotDuplicate() {
        var scheduler = RefreshScheduler()
        scheduler.trigger(.startup, at: 0)
        expectTrue(scheduler.hasPendingRefresh)
        expectNil(scheduler.nextDueAt)
        expectFalse(scheduler.beginIfDue(at: 1))
        scheduler.updateNetwork(.online, at: 2)
        expectEqual(scheduler.nextDueAt, 4)
        scheduler.trigger(.startup, at: 2.5)
        scheduler.updateNetwork(.online, at: 3)
        expectEqual(scheduler.nextDueAt, 4)
        expectFalse(scheduler.beginIfDue(at: 3.99))
        expectTrue(scheduler.beginIfDue(at: 4))
        expectFalse(scheduler.beginIfDue(at: 4))
        expectNil(scheduler.nextDueAt)
        scheduler.finish(at: 5, succeeded: true)
        scheduler.trigger(.startup, at: 5.1)
        scheduler.updateNetwork(.online, at: 5.2)
        scheduler.trigger(.periodic, at: 5.3)
        expectEqual(scheduler.nextDueAt, 305)
        expectFalse(scheduler.hasPendingRefresh)
    }

    func testWakeBurstHasBoundedDebounce() {
        var scheduler = readyScheduler()
        scheduler.trigger(.wake, at: 10)
        expectEqual(scheduler.nextDueAt, 12)
        scheduler.trigger(.wake, at: 11.5)
        expectEqual(scheduler.nextDueAt, 13.5)
        scheduler.trigger(.wake, at: 13)
        expectEqual(scheduler.nextDueAt, 14)
        scheduler.trigger(.wake, at: 13.9)
        expectEqual(scheduler.nextDueAt, 14)
        expectFalse(scheduler.beginIfDue(at: 13.99))
        expectTrue(scheduler.beginIfDue(at: 14))
        scheduler.finish(at: 15, succeeded: true)
        expectEqual(scheduler.nextDueAt, 315)
    }

    func testOfflineTriggersMergeIntoOneRecovery() {
        var scheduler = RefreshScheduler()
        scheduler.trigger(.startup, at: 0)
        scheduler.updateNetwork(.offline, at: 0.1)
        scheduler.trigger(.wake, at: 2)
        scheduler.trigger(.manual, at: 3)
        scheduler.trigger(.periodic, at: 4)
        scheduler.trigger(.wake, at: 5)
        expectNil(scheduler.nextDueAt)
        expectFalse(scheduler.beginIfDue(at: 100))
        scheduler.updateNetwork(.online, at: 100)
        expectEqual(scheduler.nextDueAt, 102)
        scheduler.updateNetwork(.online, at: 101)
        expectEqual(scheduler.nextDueAt, 102)
        expectTrue(scheduler.beginIfDue(at: 102))
        expectFalse(scheduler.hasPendingRefresh)
        scheduler.finish(at: 103, succeeded: true)
        expectEqual(scheduler.nextDueAt, 403)
    }

    func testSleepDuringRunKeepsOneSettledWakeFollowup() {
        var scheduler = RefreshScheduler()
        scheduler.updateNetwork(.online, at: 0)
        expectTrue(scheduler.beginIfDue(at: 2))
        scheduler.updateNetwork(.offline, at: 3)
        scheduler.trigger(.wake, at: 100)
        scheduler.updateNetwork(.online, at: 100.5)
        scheduler.trigger(.wake, at: 101)
        expectTrue(scheduler.hasPendingRefresh)
        expectNil(scheduler.nextDueAt)
        expectFalse(scheduler.beginIfDue(at: 110))
        scheduler.finish(at: 110, succeeded: false)
        expectEqual(scheduler.nextDueAt, 112)
        expectFalse(scheduler.beginIfDue(at: 111.99))
        expectTrue(scheduler.beginIfDue(at: 112))
        expectFalse(scheduler.hasPendingRefresh)
        scheduler.finish(at: 113, succeeded: true)
        expectEqual(scheduler.nextDueAt, 413)
    }

    func testPeriodicIsMeasuredFromCompletionAndDoesNotCatchUp() {
        var scheduler = RefreshScheduler()
        scheduler.updateNetwork(.online, at: 0)
        expectTrue(scheduler.beginIfDue(at: 2))
        scheduler.trigger(.manual, at: 3)
        scheduler.trigger(.periodic, at: 300)
        scheduler.trigger(.periodic, at: 600)
        expectFalse(scheduler.hasPendingRefresh)
        expectNil(scheduler.nextDueAt)
        scheduler.finish(at: 700, succeeded: true)
        expectEqual(scheduler.nextDueAt, 1000)
        scheduler.trigger(.periodic, at: 900)
        expectFalse(scheduler.beginIfDue(at: 999.99))
        expectTrue(scheduler.beginIfDue(at: 1000))
        expectFalse(scheduler.beginIfDue(at: 1000))
        scheduler.finish(at: 1010, succeeded: true)
        expectEqual(scheduler.nextDueAt, 1310)
        scheduler.finish(at: 1020, succeeded: true)
        expectEqual(scheduler.nextDueAt, 1310)
    }

    func testRealRecoveryAndNewWakeAreNotSuppressedAfterSuccess() {
        var scheduler = readyScheduler()
        scheduler.updateNetwork(.online, at: 3.1)
        expectEqual(scheduler.nextDueAt, 303)
        scheduler.updateNetwork(.offline, at: 3.2)
        expectNil(scheduler.nextDueAt)
        scheduler.updateNetwork(.online, at: 3.3)
        expectEqual(scheduler.nextDueAt, 5.3)
        expectTrue(scheduler.beginIfDue(at: 5.3))
        scheduler.finish(at: 6, succeeded: true)
        scheduler.trigger(.wake, at: 6.1)
        expectEqual(scheduler.nextDueAt, 8.1)
        expectTrue(scheduler.beginIfDue(at: 8.1))
    }

    func testOfflineFinishHasNoTimerUntilRecovery() {
        var scheduler = RefreshScheduler()
        scheduler.updateNetwork(.online, at: 0)
        expectTrue(scheduler.beginIfDue(at: 2))
        scheduler.updateNetwork(.unknown, at: 3)
        scheduler.finish(at: 4, succeeded: false)
        expectNil(scheduler.nextDueAt)
        expectTrue(scheduler.hasPendingRefresh)
        scheduler.updateNetwork(.offline, at: 5)
        expectNil(scheduler.nextDueAt)
        scheduler.updateNetwork(.online, at: 20)
        expectEqual(scheduler.nextDueAt, 22)
        expectTrue(scheduler.beginIfDue(at: 22))
    }

    func testFailuresBackOffAndSuccessResetsFailureCount() {
        var scheduler = RefreshScheduler()
        scheduler.updateNetwork(.online, at: 0)
        expectTrue(scheduler.beginIfDue(at: 2))
        scheduler.finish(at: 3, succeeded: false)
        expectEqual(scheduler.nextDueAt, 18)
        scheduler.updateNetwork(.online, at: 3.1)
        expectEqual(scheduler.nextDueAt, 18)
        expectFalse(scheduler.beginIfDue(at: 17.99))
        expectTrue(scheduler.beginIfDue(at: 18))
        scheduler.finish(at: 20, succeeded: false)
        expectEqual(scheduler.nextDueAt, 80)
        expectTrue(scheduler.beginIfDue(at: 80))
        scheduler.finish(at: 82, succeeded: false)
        expectEqual(scheduler.nextDueAt, 382)
        expectTrue(scheduler.beginIfDue(at: 382))
        scheduler.finish(at: 383, succeeded: false)
        expectEqual(scheduler.nextDueAt, 683)
        expectTrue(scheduler.beginIfDue(at: 683))
        scheduler.finish(at: 684, succeeded: true)
        expectEqual(scheduler.nextDueAt, 984)
        expectTrue(scheduler.beginIfDue(at: 984))
        scheduler.finish(at: 985, succeeded: false)
        expectEqual(scheduler.nextDueAt, 1000)
    }

    func testOfflineBlocksBackoffTimerAndRecoveryStillCoalesces() {
        var scheduler = RefreshScheduler()
        scheduler.updateNetwork(.online, at: 0)
        expectTrue(scheduler.beginIfDue(at: 2))
        scheduler.finish(at: 3, succeeded: false)
        expectEqual(scheduler.nextDueAt, 18)
        scheduler.updateNetwork(.offline, at: 10)
        scheduler.trigger(.periodic, at: 30)
        expectNil(scheduler.nextDueAt)
        expectFalse(scheduler.beginIfDue(at: 30))
        scheduler.updateNetwork(.online, at: 40)
        expectEqual(scheduler.nextDueAt, 42)
        expectTrue(scheduler.beginIfDue(at: 42))
        scheduler.finish(at: 44, succeeded: false)
        expectEqual(scheduler.nextDueAt, 104)
        scheduler.updateNetwork(.offline, at: 45)
        expectNil(scheduler.nextDueAt)
    }

    private func readyScheduler() -> RefreshScheduler {
        var scheduler = RefreshScheduler()
        scheduler.updateNetwork(.online, at: 0)
        _ = scheduler.beginIfDue(at: 2)
        scheduler.finish(at: 3, succeeded: true)
        return scheduler
    }
}
